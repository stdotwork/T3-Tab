import { Client } from '@modelcontextprotocol/sdk/client/index.js';
import { StdioClientTransport } from '@modelcontextprotocol/sdk/client/stdio.js';
const [cmd, names, ...args] = process.argv.slice(2);
const t = new StdioClientTransport({ command: cmd, args, stderr: 'ignore' });
const c = new Client({ name: 'x', version: '1' });
await c.connect(t);
const want = names.split(',');
for (const tool of (await c.listTools()).tools) if (want.includes(tool.name) || names === '*') console.log(tool.name, '-', tool.description?.slice(0, 300).replace(/\n/g, ' '), '\n', JSON.stringify(tool.inputSchema.properties ?? {}), 'req=', JSON.stringify(tool.inputSchema.required));
await c.close();
process.exit(0);
