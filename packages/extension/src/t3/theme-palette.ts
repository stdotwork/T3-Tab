const msg = (text: string, values?: Record<string, unknown>): string =>
  text.replace(/''/g, "'").replace(/\{(\w+)\}/g, (_, key: string) => String(values?.[key] ?? ""));
const m = (text: string): string => text;
function pipe<A>(value: A, ...steps: Array<(input: never) => unknown>): never {
  return steps.reduce<unknown>((current, step) => step(current as never), value) as never;
}

